BASE_DIR = Path(__file__).resolve().parent.parent
REPORTS_DIR = BASE_DIR / "reports"
REPORTS_DIR.mkdir(parents=True, exist_ok=True)

# In-memory execution state
_TASKS: Dict[str, Dict[str, Any]] = {}
_CACHED_RESULTS: Dict[str, Dict[str, Any]] = {}
_LOCK = threading.Lock()

def sanitize_email_key(email: str) -> str:
    """Sanitizes email to a safe filesystem key."""
    cleaned = email.strip().lower()
    return re.sub(r'[^a-zA-Z0-9_\-\.@]', '_', cleaned).replace('@', '_at_')

def _save_dossier_files(clean_key: str, data: Dict[str, Any]):
    """Saves structured JSON, formatted Markdown, and CSV dossiers with full OASIS branding."""
    email = data.get("target", clean_key)
    
    # 1. JSON Report
    json_path = REPORTS_DIR / f"email_{clean_key}.json"
    try:
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2)
    except Exception as e:
        add_log("OASIS Email Intelligence Engine", f"Failed saving JSON report: {e}", "warning")

    findings = data.get("findings", [])
    domain = data.get("domain", "")

    # 2. Markdown Dossier
    try:
        md_path = REPORTS_DIR / f"email_{clean_key}.md"
        md_lines = [
            f"# OASIS Email Intelligence Dossier — {email}",
            "",
            "> **CONFIDENTIAL INVESTIGATION PRODUCT**  ",
            "> Generated by OASIS Strategic OSINT Suite — Email Intelligence Engine  ",
            f"> **Target Email:** `{email}` | **Domain:** `{domain}` | **Generated:** {datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')}",
            "",
            "---",
            "",
            "## 1. Executive Summary",
            "",
            f"- **Target Identifier:** `{email}`",
            f"- **Platforms Surveyed:** {data.get('total_checked', 0)} online services",
            f"- **Confirmed Registrations:** **{len(findings)} accounts**",
            f"- **Rate Limits Encounted:** {data.get('total_rate_limited', 0)}",
            f"- **Triage Duration:** {data.get('duration', 0)} seconds",
            "",
            "---",
            "",
            "## 2. Confirmed Online Account Footprint",
            "",
            "| # | Platform | Target Domain | Category | Discovery Method | Leaked Recovery Data |",
            "|---|---|---|---|---|---|"
        ]

        for idx, f in enumerate(findings, 1):
            name = f.get("name", "").capitalize()
            pdomain = f.get("domain", "")
            cat = f.get("category", "general").capitalize()
            method = f.get("method", "register")
            
            leak_parts = []
            if f.get("email_recovery"):
                leak_parts.append(f"Email: `{f['email_recovery']}`")
            if f.get("phone_number"):
                leak_parts.append(f"Phone: `{f['phone_number']}`")
            if f.get("others"):
                for k, v in f["others"].items():
                    leak_parts.append(f"{k}: `{v}`")
            leak_str = "<br>".join(leak_parts) if leak_parts else "None"

            md_lines.append(f"| {idx} | **{name}** | [{pdomain}](https://{pdomain}) | `{cat}` | {method} | {leak_str} |")

        md_lines.extend([
            "",
            "---",
            "",
            "## 3. Investigation Integrity & Evidence Details",
            "",
            f"- **Engine:** OASIS Email Intelligence Engine v1.0.0",
            f"- **Platform Core:** Trio Asynchronous HTTP/2 Pipeline",
            "- **Integrity:** Non-destructive passive credential-recovery interrogation",
            ""
        ])

        with open(md_path, "w", encoding="utf-8") as f:
            f.write("\n".join(md_lines))
    except Exception as e:
        add_log("OASIS Email Intelligence Engine", f"Failed saving Markdown report: {e}", "warning")

    # 3. CSV Report
    try:
        csv_path = REPORTS_DIR / f"email_{clean_key}.csv"
        with open(csv_path, "w", newline="", encoding="utf-8") as f:
            writer = csv.writer(f)
            writer.writerow(["OASIS_Index", "Target_Email", "Platform", "Domain", "Category", "Method", "Email_Recovery", "Phone_Recovery", "Other_Details"])
            for idx, f in enumerate(findings, 1):
                writer.writerow([
                    idx,
                    email,
                    f.get("name", ""),
                    f.get("domain", ""),
                    f.get("category", ""),
                    f.get("method", ""),
                    f.get("email_recovery") or "",
                    f.get("phone_number") or "",
                    json.dumps(f.get("others") or {}) if f.get("others") else ""
                ])
    except Exception as e:
        add_log("OASIS Email Intelligence Engine", f"Failed saving CSV report: {e}", "warning")

def _background_scan_worker(email: str, clean_key: str, timeout: int):
    """Background worker executing holehe scan with live streaming telemetry."""
    task = _TASKS[clean_key]

    def progress_callback(current: int, total: int, latest: Optional[Dict[str, Any]]):
        if total > 0:
            task["progress_pct"] = int((current / total) * 100)
            task["checked_count"] = current
            task["total_count"] = total

        if latest and latest.get("exists") is True:
            item_entry = {
                "name": latest.get("name", ""),
                "domain": latest.get("domain", ""),
                "category": latest.get("category", "general"),
                "method": latest.get("method", "register"),
                "email_recovery": latest.get("emailrecovery"),
                "phone_number": latest.get("phoneNumber"),
                "others": latest.get("others")
            }
            if not any(x["name"] == item_entry["name"] for x in task["discovered_items"]):
                task["discovered_items"].append(item_entry)
                add_log("OASIS Email Intelligence Engine", f"[FOUND] Registered account on {item_entry['name']} ({item_entry['domain']})", "success")

        task["progress_msg"] = f"Surveying registries ({current}/{total}) • {len(task['discovered_items'])} accounts confirmed"

    try:
        results = execute_holehe_scan(
            email=email,
            timeout=timeout,
            progress_callback=progress_callback
        )

        _save_dossier_files(clean_key, results)

        with _LOCK:
            task["status"] = "COMPLETED"
            task["duration"] = results.get("duration", 0)
            task["findings"] = results.get("findings", [])
            task["total_checked"] = results.get("total_checked", 0)
            task["total_registered"] = results.get("total_registered", len(task["discovered_items"]))
            task["total_rate_limited"] = results.get("total_rate_limited", 0)
            task["total_errors"] = results.get("total_errors", 0)
            task["progress_pct"] = 100
            task["progress_msg"] = f"Triage complete. {len(task['findings'])} accounts confirmed across {task['total_checked']} platforms in {task['duration']}s."
            _CACHED_RESULTS[clean_key] = results

        add_log("OASIS Email Intelligence Engine", f"Reconnaissance completed for {email}: {len(task['findings'])} accounts identified.", "success")
        update_tool_notification(
            "OASIS Email Intelligence Engine",
            email,
            "FINISHED",
            details=f"Identified {len(task['findings'])} registered accounts in {task['duration']}s"
        )
    except Exception as e:
        with _LOCK:
            task["status"] = "ERROR"
            task["error"] = str(e)
            task["progress_msg"] = f"Error: {e}"
        add_log("OASIS Email Intelligence Engine", f"Execution error for {email}: {e}", "error")
        update_tool_notification(
            "OASIS Email Intelligence Engine",
            email,
            "ERROR",
            details=f"Engine error: {e}"
        )

def execute_email_recon(email: str, force: bool = False, timeout: int = 10) -> Dict[str, Any]:
    """Dispatches asynchronous email intelligence scan or serves from local vault cache."""
    email_clean = email.strip()
    if not is_valid_email(email_clean):
        raise ValueError(f"Invalid email address format: '{email_clean}'")

    clean_key = sanitize_email_key(email_clean)

    # Check cache if not forced
    if not force:
        cached_file = REPORTS_DIR / f"email_{clean_key}.json"
        if cached_file.exists():
            try:
                with open(cached_file, "r", encoding="utf-8") as f:
                    cached_data = json.load(f)
                return {
                    "status": "COMPLETED",
                    "cached": True,
                    "target": email_clean,
                    "domain": cached_data.get("domain", ""),
                    "duration": 0.1,
                    "findings": cached_data.get("findings", []),
                    "total_checked": cached_data.get("total_checked", 0),
                    "total_registered": cached_data.get("total_registered", 0),
                    "progress_msg": f"Loaded cached OASIS Email dossier ({len(cached_data.get('findings', []))} accounts confirmed)."
                }
            except Exception:
                pass

    with _LOCK:
        if clean_key in _TASKS and _TASKS[clean_key].get("status") == "RUNNING":
            t = _TASKS[clean_key]
            return {
                "status": "RUNNING",
                "target": email_clean,
                "elapsed": round(time.time() - t["start_time"], 1),
                "progress_pct": t.get("progress_pct", 15),
                "progress_msg": t.get("progress_msg", "Reconnaissance in progress..."),
                "discovered_items": t.get("discovered_items", [])
            }

        task_record = {
            "target": email_clean,
            "status": "RUNNING",
            "start_time": time.time(),
            "duration": 0,
            "progress_pct": 10,
            "progress_msg": f"Connecting to 120+ registries for {email_clean}...",
            "discovered_items": [],
            "findings": [],
            "error": None
        }
        _TASKS[clean_key] = task_record

    add_log("OASIS Email Intelligence Engine", f"Starting email reconnaissance on: {email_clean}", "info")
    update_tool_notification("OASIS Email Intelligence Engine", email_clean, "PROCESSING", details="Surveying online platforms...")

    worker = threading.Thread(
        target=_background_scan_worker,
        args=(email_clean, clean_key, timeout),
        daemon=True
    )
    worker.start()

    return {
        "status": "RUNNING",
        "target": email_clean,
        "elapsed": 0,
        "progress_pct": 10,
        "progress_msg": f"OASIS Email Engine dispatched to background worker for {email_clean}."
    }

def get_email_status(email: str) -> Dict[str, Any]:
    """Retrieves live running telemetry or cached results for an email target."""
    clean_key = sanitize_email_key(email)
    
    if clean_key in _TASKS:
        t = _TASKS[clean_key]
        elapsed = round(time.time() - t["start_time"], 1) if t["status"] == "RUNNING" else t.get("duration", 0)
        return {
            "target": t["target"],
            "status": t["status"],
            "elapsed": elapsed,
            "progress_pct": t.get("progress_pct", 0),
            "progress_msg": t.get("progress_msg", ""),
            "discovered_items": t.get("discovered_items", []),
            "findings": t.get("findings", []),
            "total_checked": t.get("total_checked", 0),
            "total_registered": t.get("total_registered", len(t.get("discovered_items", []))),
            "error": t.get("error")
        }

    cached_file = REPORTS_DIR / f"email_{clean_key}.json"
    if cached_file.exists():
        try:
            with open(cached_file, "r", encoding="utf-8") as f:
                data = json.load(f)
            return {
                "target": email,
                "status": "COMPLETED",
                "cached": True,
                "elapsed": 0.1,
                "progress_pct": 100,
                "progress_msg": f"Retrieved from internal OASIS vault ({len(data.get('findings', []))} accounts).",
                "discovered_items": data.get("findings", []),
                "findings": data.get("findings", []),
                "total_checked": data.get("total_checked", 0),
                "total_registered": data.get("total_registered", 0),
                "error": None
            }
        except Exception:
            pass

    return {
        "target": email,
        "status": "IDLE",
        "elapsed": 0,
        "progress_pct": 0,
        "progress_msg": "Ready to scan.",
        "discovered_items": [],
        "findings": [],
        "error": None
    }

def ensure_email_report_file(email: str, fmt: str = "json") -> Optional[Path]:
    """Returns filesystem path for download of requested dossier format."""
    clean_key = sanitize_email_key(email)
    fmt = fmt.lower().strip()
    if fmt == "csv":
        p = REPORTS_DIR / f"email_{clean_key}.csv"
        if p.exists(): return p
    elif fmt == "md":
        p = REPORTS_DIR / f"email_{clean_key}.md"
        if p.exists(): return p
    else:
        p = REPORTS_DIR / f"email_{clean_key}.json"
        if p.exists(): return p
    return None

def get_recent_email_scans() -> List[Dict[str, Any]]:
    """Lists historical email intelligence scans stored in the vault."""
    history = []
    for f in REPORTS_DIR.glob("email_*.json"):
        try:
            with open(f, "r", encoding="utf-8") as jf:
                data = json.load(jf)
            history.append({
                "target": data.get("target", f.stem.replace("email_", "")),
                "total_registered": len(data.get("findings", [])),
                "duration": data.get("duration", 0),
                "timestamp": data.get("timestamp", "")
            })
        except Exception:
            pass
    return sorted(history, key=lambda x: x.get("timestamp", ""), reverse=True)[:15]
